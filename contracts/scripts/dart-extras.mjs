// Writes what quicktype does not for Dart: a decoder that picks the message class by `type`,
// and the schema -> class table the shared package's contract test walks.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { messageFiles, modelFiles, readJson } from "./schemas.mjs";

const [libDir, testDir] = process.argv.slice(2);
const HEADER = "// Generated by contracts/scripts/codegen.sh from contracts/*.json. Do not edit.\n\n";

const cases = messageFiles()
  .map((rel) => `  '${readJson(rel).properties.type.const}' => ${readJson(rel).title}.fromJson(json),\n`)
  .join("");
writeFileSync(
  join(libDir, "messages.dart"),
  `${HEADER}import 'contracts.dart';\n\n` +
    "/// Decodes a WebSocket message into its generated class, chosen by `type`.\n" +
    "///\n" +
    "/// Returns null for a type this build does not know (a newer server or camera).\n" +
    "/// Throws when a known message does not match its schema.\n" +
    `Object? decodeMessage(Map<String, dynamic> json) => switch (json['type']) {\n${cases}  _ => null,\n};\n`,
);

const entries = modelFiles()
  .map((rel) => `  '${rel}': (json) => ${readJson(rel).title}.fromJson(json).toJson(),\n`)
  .join("");
writeFileSync(
  join(testDir, "contract_models.dart"),
  `${HEADER}import 'package:shared/src/contracts/contracts.dart';\n\n` +
    "/// Schema path -> decode with the generated class and encode again.\n" +
    `final contractModels = <String, Map<String, dynamic> Function(Map<String, dynamic>)>{\n${entries}};\n`,
);
