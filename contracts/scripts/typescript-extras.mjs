// Writes what quicktype does not: the schemas as a module (media-server validates messages without
// reading contracts/) and the union of all WebSocket message types.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { messageFiles, readJson, schemaFiles } from "./schemas.mjs";

const [outDir] = process.argv.slice(2);
const HEADER = "// Generated by contracts/scripts/codegen.sh from contracts/*.json. Do not edit.\n\n";

const schemas = Object.fromEntries(schemaFiles().map((rel) => [rel, readJson(rel)]));
writeFileSync(join(outDir, "schemas.ts"), `${HEADER}export const schemas: Record<string, object> = ${JSON.stringify(schemas, null, 2)};\n`);

const messages = messageFiles().map((rel) => ({ type: readJson(rel).properties.type.const, title: readJson(rel).title }));
const titles = messages.map((m) => m.title);
writeFileSync(
  join(outDir, "messages.ts"),
  HEADER +
    `import type {\n${titles.map((t) => `  ${t},\n`).join("")}} from "./types.js";\n\n` +
    "/** Every WebSocket message; narrow it by `type`. */\n" +
    `export type Message =\n${titles.map((t) => `  | ${t}`).join("\n")};\n\n` +
    `export type MessageType = Message["type"];\n`,
);
